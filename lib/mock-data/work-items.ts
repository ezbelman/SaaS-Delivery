export const getWorkItemChildren = (items: WorkItem[], parentId?: string): WorkItem[] =>
  items.filter((i) => i.parentId === parentId).sort((a, b) => a.position - b.position)

export const getTopLevelItems = (items: WorkItem[]): WorkItem[] =>
  items.filter((i) => !i.parentId).sort((a, b) => a.position - b.position)

export const flattenTree = (items: WorkItem[], parentId?: string): WorkItem[] => {
  const children = getWorkItemChildren(items, parentId)
  return children.flatMap((child) => [child, ...flattenTree(items, child.id)])
}
